// Regenerates src/demo/routes.generated.ts — the route table the in-browser demo backend
// (GitHub Pages build) uses to dispatch /api/* calls to the same route handlers the server runs.
// Run after adding or removing an API route:  node scripts/gen-demo-routes.mjs
import fs from "node:fs";
import path from "node:path";

const root = "src/app/api";
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (f === "route.ts") files.push(p.split(path.sep).join("/"));
  }
})(root);

// Static segments before dynamic ones so /devices/bulk wins over /devices/[id].
const dyn = (f) => (f.match(/\[/g) ?? []).length;
files.sort((a, b) => dyn(a) - dyn(b) || a.localeCompare(b));

const imports = [];
const rows = [];
files.forEach((f, i) => {
  const mod = f.replace(/^src\//, "@/").replace(/\/route\.ts$/, "/route");
  const url = f.replace(/^src\/app/, "").replace(/\/route\.ts$/, "");
  imports.push(`import * as r${i} from "${mod}";`);
  rows.push(`  ["${url}", r${i}],`);
});

const out = `// Generated by scripts/gen-demo-routes.mjs — do not edit by hand.
${imports.join("\n")}

export const ROUTES: [string, Record<string, unknown>][] = [
${rows.join("\n")}
];
`;
fs.mkdirSync("src/demo", { recursive: true });
fs.writeFileSync("src/demo/routes.generated.ts", out);
console.log(`wrote ${files.length} routes`);
